#!/usr/bin/env python3
"""Emit only approved declaration names from the local v39 offline catalog."""
import argparse
import gzip
import json
from pathlib import Path

# Type names are unique in the 0.437.0 definitions for this allowlist.
ALLOW = {
    "IPlayerService": ("", "PlayerStats LevelProgress Incubators MaxItems MaxPokemon", "get_PlayerStats get_LevelProgress"),
    "PlayerStatsProto": ("Level Experience PrevLevelExp NextLevelExp KmWalked NumPokemonEncountered NumPokemonCaptured PokeStopVisits NumEggsHatched", "", ""),
    "IPokemonBag": ("", "AllPokemon Count PokemonOnlyCount EggCount", "get_Count get_PokemonOnlyCount get_EggCount"),
    "PokemonProto": ("cp_ stamina_ maxStamina_ nickname_", "Form IsShinyPokemon IsShadowPokemon", "get_IsShinyPokemon get_IsShadowPokemon"),
    "PokemonDisplayProto": ("Gender Shiny Form Alignment", "IsMegaEvolved", "get_IsMegaEvolved"),
    "IItemBag": ("", "AllItems", "GetItemCount GetTotalItems"),
    "EggIncubatorProto": ("IncubatorType UsesRemaining StartKmWalked TargetKmWalked", "", ""),
    "IPokedex": ("", "", "GetTimesEncountered GetTimesCaptured"),
    "PokedexEntryProto": ("TimesEncountered TimesCaptured CapturedShiny EncounteredShiny", "", ""),
    "IActivityLogService": ("", "", ""),
    "ActionLogEntry": ("TimestampMs", "CatchPokemon FortSearch", ""),
    "PokemonGender": ("", "", ""),
}

def type_name(ref):
    if not ref or "name" not in ref:
        return None
    return ".".join(filter(None, (ref.get("namespace"), ref["name"])))

def declarations(path):
    found = {}
    with gzip.open(path, "rt", encoding="utf-8") as source:
        for line in source:
            row = json.loads(line)
            name = row["name"]
            if name not in ALLOW or (name == "PokemonGender" and row["image"] != "holo-protos.dll"):
                continue
            if name in found:
                raise ValueError(f"Ambiguous declaration {name}")
            fields, props, methods = (set(group.split()) for group in ALLOW[name])
            found[name] = {
                "id": name, "assembly": row["image"], "namespace": row["namespace"],
                "kind": row["kind"], "provenance": "offline_v39_0.437.0",
                "fields": [{"name": x["name"], "type": type_name(x["type"])}
                           for x in row["fields"] if x["name"] in fields],
                "properties": [{"name": x["name"], "type": type_name(x.get("type"))}
                               for x in row["properties"] if x["name"] in props],
                "methods": [{"name": x["name"], "returns": type_name(x["return_type"]),
                             "parameters": [type_name(p["type"]) for p in x["parameters"]]}
                            for x in row["methods"] if x["name"] in methods],
                "enumerators": row["enum_members"] if row["kind"] == "enum" else [],
            }
    if found.keys() != ALLOW.keys():
        raise ValueError(f"Missing declarations: {sorted(ALLOW.keys() - found.keys())}")
    return [found[name] for name in sorted(found)]

def java(rows):
    lines = ["package dev.pgrazor;", "", "// Generated by scripts/research/export-api-declarations.py.",
             "final class ResearchDeclarations {", "    static final String[][] TYPES = {"]
    for row in rows:
        details = json.dumps(row, separators=(",", ":"), ensure_ascii=True)
        lines.append("        {" + ", ".join(json.dumps(s) for s in (
            row["id"], row["assembly"], row["namespace"], details)) + "},")
    return "\n".join(lines + ["    };", "    private ResearchDeclarations() {}", "}", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("--format", choices=("java", "json"), default="java")
    options = parser.parse_args()
    rows = declarations(options.catalog)
    print(java(rows) if options.format == "java" else json.dumps(rows), end="\n" if options.format == "json" else "")
